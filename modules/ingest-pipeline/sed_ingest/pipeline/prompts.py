DOC_OPEN, DOC_CLOSE = "<<<ДОКУМЕНТ>>>", "<<<КІНЕЦЬ ДОКУМЕНТА>>>"
_GAP = "\n[… фрагмент документа пропущено …]\n"


def fit_to_budget(text: str, max_chars: int) -> tuple[str, bool]:
    """Реквізити зосереджені на початку (вид, дата, номер, заголовок) і в кінці (підпис, візи,
    ознайомлення), тому для довгих документів лишаємо 70 % початку і 30 % кінця."""
    if len(text) <= max_chars:
        return text, False
    head = int(max_chars * 0.7)
    tail = max_chars - head - len(_GAP)
    return text[:head] + _GAP + text[-tail:], True


def build_user_prompt(masked_text: str, today: date, max_chars: int) -> tuple[str, bool]:
    body, truncated = fit_to_budget(masked_text, max_chars)
    # Текст не може «закрити» блок даних власним маркером.
    body = body.replace("<<<", "‹‹‹").replace(">>>", "›››")
    return (
        f"Сьогодні {today.strftime('%d.%m.%Y')}. Вилучи реквізити з документа.\n\n"
        f"{DOC_OPEN}\n{body}\n{DOC_CLOSE}",
        truncated,
    )
